// File: generate-code-index.mjs
// Purpose: Generate or verify exact source declaration line locations for maintainable documentation.
// Functions: collectFiles, declarationsFor, render, and main.
// Variables: roots, files, and output hold repository-relative documentation inputs.

import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const repositoryRoot = path.resolve(import.meta.dirname, "..");
const roots = ["src", "tests", "unity/Assets/TacticalAI"];
const outputPath = path.join(repositoryRoot, "docs", "CODE_INDEX.md");

function collectFiles(directory) {
  if (!fs.existsSync(directory)) {
    return [];
  }

  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(directory, entry.name);
    return entry.isDirectory() ? collectFiles(absolute) : entry.name.endsWith(".cs") ? [absolute] : [];
  });
}

function declarationsFor(filePath) {
  const lines = fs.readFileSync(filePath, "utf8").split(/\r?\n/u);
  const declarationPattern = /^\s*(?:public|internal|private|protected)\s+(?:(?:static|sealed|abstract|readonly|partial|async|virtual|override)\s+)*(?:class|struct|enum|interface|record|void|[A-Z][\w<>,?\[\].]*)\s+([A-Za-z_]\w*)/u;
  return lines.flatMap((line, index) => {
    const match = declarationPattern.exec(line);
    return match ? [{ line: index + 1, symbol: match[1], signature: line.trim().replace(/\s*\{?\s*$/u, "") }] : [];
  });
}

function render() {
  const files = roots.flatMap((root) => collectFiles(path.join(repositoryRoot, root)))
    .sort((left, right) => left.localeCompare(right, "en"));
  const sections = files.map((filePath) => {
    const relative = path.relative(repositoryRoot, filePath).replaceAll("\\", "/");
    const declarations = declarationsFor(filePath);
    const tableRows = declarations.length === 0
      ? "| — | — | No indexed declarations |"
      : declarations.map((item) => `| ${item.line} | \`${item.symbol}\` | \`${item.signature.replaceAll("|", "\\|")}\` |`).join("\n");
    return `## \`${relative}\`\n\n| Line | Symbol | Declaration |\n| ---: | --- | --- |\n${tableRows}`;
  });
  return `# Code declaration index\n\nGenerated by \`scripts/generate-code-index.mjs\`. Line numbers are exact for this commit and replace brittle, duplicated line annotations inside source headers.\n\n${sections.join("\n\n")}\n`;
}

function main() {
  const generated = render();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
    if (current !== generated) {
      console.error("docs/CODE_INDEX.md is stale; run node scripts/generate-code-index.mjs.");
      process.exitCode = 1;
    }
    return;
  }

  fs.writeFileSync(outputPath, generated, "utf8");
  console.log(`generated ${path.relative(repositoryRoot, outputPath)}`);
}

main();
